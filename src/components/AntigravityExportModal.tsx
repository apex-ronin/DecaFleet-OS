import React, { useState } from 'react';
import { BUSINESS_HANDBOOKS } from '../data/handbooks.ts';
import { X, Copy, Check, Download, Terminal, Bot, FolderGit2, Cpu, ShieldCheck } from 'lucide-react';

interface AntigravityExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  selectedBusinessId: string;
  onExportMasterBlueprint: () => void;
}

export const AntigravityExportModal: React.FC<AntigravityExportModalProps> = ({
  isOpen,
  onClose,
  selectedBusinessId,
  onExportMasterBlueprint
}) => {
  const [activeMode, setActiveMode] = useState<'codebase' | 'agents' | 'runtimes'>('codebase');
  const [targetScope, setTargetScope] = useState<string>(selectedBusinessId);
  const [selectedRuntime, setSelectedRuntime] = useState<'invisible_dots' | 'openmausbot' | 'hybrid'>('hybrid');
  const [copiedCmd, setCopiedCmd] = useState(false);
  const [copiedSpec, setCopiedSpec] = useState(false);
  const [copiedRuntime, setCopiedRuntime] = useState(false);

  if (!isOpen) return null;

  const selectedHandbook =
    BUSINESS_HANDBOOKS.find((b) => b.id === targetScope) || BUSINESS_HANDBOOKS[1];

  const generateAntigravityAgentSpec = () => {
    const list = targetScope === 'all' ? BUSINESS_HANDBOOKS : [selectedHandbook];

    let spec = `# ANTIGRAVITY / OPENMAUSBOT / INVISIBLE_DOTS WORKSPACE SPEC (AGENTS.md)
# Generated by DecaFleet OS — 10-Bot Autonomous Enterprise Architecture
# Shared Filesystem: /shared/data/ | Max Concurrency: 10 Browser Sessions | Human Cap: 20h/wk

`;

    list.forEach((hb) => {
      spec += `================================================================================
## FLEET PROFILE: ${hb.code} — ${hb.name} (${hb.label})
Thesis: ${hb.oneLineThesis}
================================================================================

### 1. AGENT SYSTEM PROMPTS (10-BOT ALLOCATION)
${hb.botFleet
  .map(
    (b) => `#### Agent: ${b.name} (${b.role})
- **Capability:** ${b.capability}
- **Approval Gate:** ${b.approvalBoundary}
- **System Prompt:**
\`\`\`text
${b.jobDescription}
\`\`\``
  )
  .join('\n\n')}

### 2. EXECUTABLE SKILLS & ACCEPTANCE TESTS (SKILL.md)
${hb.skillsToBuild
  .map(
    (s) => `#### Skill #${s.order}: ${s.title}
- **Spec:** ${s.description}
- **Deterministic Acceptance Test:** ${s.acceptanceTest}`
  )
  .join('\n\n')}

### 3. SCHEDULED ROUTINES & FAILURE HANDLERS
| Bot | Trigger | Input | Output Artifact | Approval Gate | Failure Recovery |
|---|---|---|---|---|---|
${hb.routines
  .map(
    (r) =>
      `| ${r.bot} | ${r.trigger} | ${r.inputSource} | ${r.outputArtifact} | ${r.approvalGate} | ${r.failureBehaviour} |`
  )
  .join('\n')}

`;
    });

    return spec;
  };

  const generateRuntimeConfig = () => {
    if (selectedRuntime === 'invisible_dots') {
      return `# feder-cr/invisible_dots — Stealth Browser & OpenRouter Config
# Repo: https://github.com/feder-cr/invisible_dots
# Best for: Scraping-heavy bots (JobSpy-01,StackDetect-02, BidScout-01, SERPHound-01)
# Why: Patched Firefox (invisible_playwright_mcp) bypasses Cloudflare/DataDome; OpenRouter avoids Grok weekly caps.

export OPENROUTER_API_KEY="sk-or-v1-YOUR_KEY"
# Cost-control routing: Use DeepSeek-V3 / Gemini-2.5-Flash for DOM parsing ($0.14/1M tokens)
# instead of burning $15 Grok trial quotas in 72 hours.
export DOTS_DEFAULT_MODEL="google/gemini-2.5-flash"
export DOTS_REASONING_MODEL="deepseek/deepseek-chat-v3-0324"
export DOTS_MAX_CONCURRENT_VMS=4 # Keep QEMU RAM under 16GB on a single host
export DOTS_SHARED_MOUNT="/shared/data"
export DOTS_BROWSER_ENGINE="invisible_playwright_mcp"

# Launch 4 Stealth Scraper Dots for ${selectedHandbook.code} (${selectedHandbook.name}):
${selectedHandbook.botFleet
  .slice(0, 4)
  .map(
    (b, idx) =>
      `dots spawn --name "${b.name}" --vm-ram 2048 --mcp "invisible_playwright_mcp" --approval-webhook "http://localhost:3000/api/gate" # Role: ${b.role}`
  )
  .join('\n')}`;
    }

    if (selectedRuntime === 'openmausbot') {
      return JSON.stringify(
        {
          $schema: 'https://github.com/milind-soni/OpenMausBot/team-schema.json',
          teamName: `DecaFleet_${selectedHandbook.code}_${selectedHandbook.name.split(' ')[0]}`,
          sharedWorkspace: '/shared/data',
          permissionBroker: {
            requireInlineApprovalFor: ['external_http_post', 'smtp_send', 'portal_submit', 'sms_2fa'],
            autoApproveReadOnlyShell: true
          },
          agents: selectedHandbook.botFleet.map((b) => ({
            id: b.name.toLowerCase(),
            name: b.name,
            role: b.role,
            cliBackend: 'openrouter-cli',
            fallbackCli: 'grok-cli',
            capability: b.capability,
            approvalGate: b.approvalBoundary,
            systemPrompt: b.jobDescription
          }))
        },
        null,
        2
      );
    }

    return `# RECOMMENDED HYBRID STACK: OpenMausBot (Orchestrator) + invisible_dots (Stealth Browser Workers)
# Why Grok Bot maxed out in <3 days: Vision-based computer-use screenshots consume 4,000-12,000 tokens per click.
# Running 10 bots on continuous cron loops burns a $15 quota in ~48-72 hours.

## LAYER 1: Control Plane & Human Gate -> milind-soni/OpenMausBot
- Use OpenMausBot as your local-first group chat, memory store, and Permission Broker UI.
- Route 80% of text/CSV/enrichment tasks (Normalize-01, Icebreak-01, FormPrep-01, Digest-01) through cheap OpenRouter / Gemini Flash / DeepSeek APIs ($2-$4/week total).
- Reserve your $15 Grok trial ONLY for final complex reasoning or edge-case copy generation.

## LAYER 2: Stealth Browser Execution -> feder-cr/invisible_dots (invisible_playwright_mcp)
- Do NOT run 10 simultaneous QEMU VMs (requires 32GB+ RAM).
- Instead, run OpenMausBot on your host machine and attach feder-cr's \`invisible_playwright_mcp\` server directly to your 3-4 scraping bots (${selectedHandbook.botFleet.slice(0, 3).map((b) => b.name).join(', ')}).
- Use DOM/accessibility-tree extraction via MCP before taking screenshots — cuts token burn by 88% while bypassing Cloudflare/DataDome.`;
  };

  const agentSpecText = generateAntigravityAgentSpec();
  const runtimeConfigText = generateRuntimeConfig();

  const handleCopySetupCmd = () => {
    navigator.clipboard.writeText(`npm install && npm run dev`);
    setCopiedCmd(true);
    setTimeout(() => setCopiedCmd(false), 2000);
  };

  const handleCopyAgentSpec = () => {
    navigator.clipboard.writeText(agentSpecText);
    setCopiedSpec(true);
    setTimeout(() => setCopiedSpec(false), 2000);
  };

  const handleCopyRuntime = () => {
    navigator.clipboard.writeText(runtimeConfigText);
    setCopiedRuntime(true);
    setTimeout(() => setCopiedRuntime(false), 2000);
  };

  const handleDownloadAgentSpec = () => {
    const blob = new Blob([agentSpecText], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download =
      targetScope === 'all'
        ? 'AGENTS_ALL_6_FLEETS.md'
        : `AGENTS_${selectedHandbook.code}_${selectedHandbook.name.split(' ')[0]}.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div
      className="fixed inset-0 z-50 bg-slate-950/70 flex items-center justify-center p-4"
      role="dialog"
      aria-modal="true"
      aria-labelledby="antigravity-export-title"
    >
      <div className="bg-white border border-slate-200 rounded-lg max-w-3xl w-full shadow-lg overflow-hidden flex flex-col max-h-[90vh]">
        {/* Modal Header */}
        <div className="px-6 py-4 bg-slate-900 text-white flex items-center justify-between">
          <div>
            <h2 id="antigravity-export-title" className="text-base font-bold">
              Export to Antigravity &amp; Open-Source Bot Runtimes
            </h2>
            <p className="text-xs text-slate-400">
              Export the full React/Vite app to Google Antigravity, or generate configs for invisible_dots &amp; OpenMausBot.
            </p>
          </div>
          <button
            onClick={onClose}
            aria-label="Close export modal"
            className="text-slate-400 hover:text-white p-1 rounded cursor-pointer"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        {/* Mode Switcher */}
        <div className="px-6 pt-4 pb-2 border-b border-slate-200 bg-slate-50 flex items-center justify-between flex-wrap gap-2">
          <div className="flex items-center gap-1 p-1 bg-slate-200/80 rounded-lg text-xs flex-wrap">
            <button
              onClick={() => setActiveMode('codebase')}
              className={`px-3 py-1.5 font-medium rounded-md transition-colors flex items-center gap-1.5 cursor-pointer ${
                activeMode === 'codebase'
                  ? 'bg-white text-slate-900 shadow-2xs font-semibold'
                  : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              <FolderGit2 className="w-3.5 h-3.5" />
              <span>1. Export App to Antigravity</span>
            </button>
            <button
              onClick={() => setActiveMode('runtimes')}
              className={`px-3 py-1.5 font-medium rounded-md transition-colors flex items-center gap-1.5 cursor-pointer ${
                activeMode === 'runtimes'
                  ? 'bg-white text-slate-900 shadow-2xs font-semibold'
                  : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              <Cpu className="w-3.5 h-3.5" />
              <span>2. invisible_dots / OpenMausBot</span>
            </button>
            <button
              onClick={() => setActiveMode('agents')}
              className={`px-3 py-1.5 font-medium rounded-md transition-colors flex items-center gap-1.5 cursor-pointer ${
                activeMode === 'agents'
                  ? 'bg-white text-slate-900 shadow-2xs font-semibold'
                  : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              <Bot className="w-3.5 h-3.5" />
              <span>3. AGENTS.md / SKILL.md</span>
            </button>
          </div>

          <button
            onClick={onExportMasterBlueprint}
            className="text-xs font-medium text-slate-600 hover:text-slate-900 flex items-center gap-1 cursor-pointer"
          >
            <Download className="w-3.5 h-3.5" />
            <span>Master Blueprint (.md)</span>
          </button>
        </div>

        {/* Modal Body */}
        <div className="p-6 overflow-y-auto space-y-5 text-xs sm:text-sm">
          {activeMode === 'codebase' && (
            <div className="space-y-4">
              <div className="p-4 bg-slate-50 border border-slate-200 rounded-lg space-y-2">
                <div className="font-bold text-slate-900">
                  Step-by-Step: Export Whole App Project into Google Antigravity (ZIP Method)
                </div>
                <ol className="list-decimal list-inside space-y-1.5 text-xs text-slate-700 leading-relaxed">
                  <li>
                    Look at the <strong>top-right header bar of the Google AI Studio window</strong> (outside and right above this preview panel).
                  </li>
                  <li>
                    Click the <strong>Download ZIP icon</strong> (downward arrow icon) to download the entire project file tree (<code>package.json</code>, <code>src/</code>, <code>vite.config.ts</code>, all 6 handbooks, and unit tests).
                  </li>
                  <li>
                    Unzip the downloaded file on your PC (e.g., <code>C:\Projects\decafleet-os</code> or <code>~/decafleet-os</code>).
                  </li>
                  <li>
                    Launch <strong>Google Antigravity</strong> and select <strong>File &rarr; Open Folder...</strong> (or run <code>agy ./decafleet-os</code> in your terminal).
                  </li>
                </ol>
              </div>

              <div className="p-4 bg-slate-50 border border-slate-200 rounded-lg space-y-2">
                <div className="font-bold text-slate-900">
                  Alternative: Direct GitHub Sync &rarr; Antigravity Clone
                </div>
                <ol className="list-decimal list-inside space-y-1.5 text-xs text-slate-700 leading-relaxed">
                  <li>
                    Click the <strong>GitHub icon</strong> in the top-right Google AI Studio toolbar to push this project directly to a new GitHub repo.
                  </li>
                  <li>
                    In <strong>Antigravity</strong>, press <code>Ctrl+Shift+P</code> (or <code>Cmd+Shift+P</code>) &rarr; <strong>Git: Clone</strong> and paste your GitHub repository URL.
                  </li>
                </ol>
              </div>

              <div className="p-4 bg-slate-900 text-slate-100 rounded-lg space-y-2 font-mono text-xs">
                <div className="flex items-center justify-between">
                  <span className="text-slate-400 flex items-center gap-1.5">
                    <Terminal className="w-3.5 h-3.5 text-emerald-400" />
                    <span>Once opened inside Antigravity, run in the terminal:</span>
                  </span>
                  <button
                    onClick={handleCopySetupCmd}
                    className="px-2.5 py-1 bg-slate-800 hover:bg-slate-700 text-slate-200 rounded text-[11px] flex items-center gap-1 cursor-pointer"
                  >
                    {copiedCmd ? <Check className="w-3 h-3 text-emerald-400" /> : <Copy className="w-3 h-3" />}
                    <span>{copiedCmd ? 'Copied' : 'Copy Command'}</span>
                  </button>
                </div>
                <pre className="text-emerald-400 overflow-x-auto">
{`# Install packages and launch local dev server on http://localhost:3000
npm install && npm run dev

# Verify the pure-logic unit test suite
node --test src/utils/calculator.test.ts`}
                </pre>
              </div>
            </div>
          )}

          {activeMode === 'runtimes' && (
            <div className="space-y-4">
              <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
                <div className="flex items-center gap-1.5">
                  <button
                    onClick={() => setSelectedRuntime('hybrid')}
                    className={`px-2.5 py-1 text-xs font-semibold rounded cursor-pointer ${
                      selectedRuntime === 'hybrid'
                        ? 'bg-slate-900 text-white'
                        : 'bg-slate-100 text-slate-700 hover:bg-slate-200'
                    }`}
                  >
                    Recommended Hybrid Stack
                  </button>
                  <button
                    onClick={() => setSelectedRuntime('invisible_dots')}
                    className={`px-2.5 py-1 text-xs font-semibold rounded cursor-pointer ${
                      selectedRuntime === 'invisible_dots'
                        ? 'bg-slate-900 text-white'
                        : 'bg-slate-100 text-slate-700 hover:bg-slate-200'
                    }`}
                  >
                    feder-cr/invisible_dots
                  </button>
                  <button
                    onClick={() => setSelectedRuntime('openmausbot')}
                    className={`px-2.5 py-1 text-xs font-semibold rounded cursor-pointer ${
                      selectedRuntime === 'openmausbot'
                        ? 'bg-slate-900 text-white'
                        : 'bg-slate-100 text-slate-700 hover:bg-slate-200'
                    }`}
                  >
                    milind-soni/OpenMausBot
                  </button>
                </div>

                <button
                  onClick={handleCopyRuntime}
                  className="px-3 py-1.5 text-xs font-semibold bg-slate-100 hover:bg-slate-200 text-slate-800 rounded-md flex items-center gap-1.5 cursor-pointer"
                >
                  {copiedRuntime ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Copy className="w-3.5 h-3.5" />}
                  <span>{copiedRuntime ? 'Copied Config' : 'Copy Runtime Config'}</span>
                </button>
              </div>

              <div className="p-3.5 bg-amber-50 border border-amber-200 rounded-lg text-xs text-amber-950 flex items-start gap-2.5">
                <ShieldCheck className="w-4 h-4 text-amber-700 shrink-0 mt-0.5" />
                <div>
                  <strong>Why Grok Bot maxed out in under 3 days:</strong> Continuous screenshot-based computer-use loops burn 4,000–12,000 vision tokens per click. By pairing <strong>OpenMausBot</strong> (Permission Broker &amp; multi-bot chat) with <strong>invisible_dots&apos;s</strong> <code>invisible_playwright_mcp</code> over OpenRouter (DeepSeek V3 / Gemini Flash), you cut token burn by ~88% and bypass Cloudflare/DataDome.
                </div>
              </div>

              <pre className="p-4 bg-slate-950 text-slate-200 rounded-lg font-mono text-[11px] h-64 overflow-y-auto whitespace-pre-wrap leading-relaxed">
                {runtimeConfigText}
              </pre>
            </div>
          )}

          {activeMode === 'agents' && (
            <div className="space-y-4">
              <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
                <div className="flex items-center gap-2">
                  <label htmlFor="antigravity-scope-select" className="text-xs font-semibold text-slate-700">
                    Select Agent Fleet Scope:
                  </label>
                  <select
                    id="antigravity-scope-select"
                    value={targetScope}
                    onChange={(e) => setTargetScope(e.target.value)}
                    className="text-xs font-semibold bg-white border border-slate-300 rounded px-2.5 py-1.5 text-slate-900 cursor-pointer"
                  >
                    <option value="all">All 6 Business Fleets (60 Bot Roles)</option>
                    {BUSINESS_HANDBOOKS.map((b) => (
                      <option key={b.id} value={b.id}>
                        {b.code}: {b.name}
                      </option>
                    ))}
                  </select>
                </div>

                <div className="flex items-center gap-2">
                  <button
                    onClick={handleCopyAgentSpec}
                    className="px-3 py-1.5 text-xs font-semibold bg-slate-100 hover:bg-slate-200 text-slate-800 rounded-md flex items-center gap-1.5 cursor-pointer"
                  >
                    {copiedSpec ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Copy className="w-3.5 h-3.5" />}
                    <span>{copiedSpec ? 'Copied AGENTS.md' : 'Copy AGENTS.md'}</span>
                  </button>
                  <button
                    onClick={handleDownloadAgentSpec}
                    className="px-3.5 py-1.5 text-xs font-semibold bg-slate-900 hover:bg-slate-800 text-white rounded-md flex items-center gap-1.5 cursor-pointer"
                  >
                    <Download className="w-3.5 h-3.5" />
                    <span>Download AGENTS.md</span>
                  </button>
                </div>
              </div>

              <p className="text-xs text-slate-600">
                Drop this file into your Antigravity project root as <code>AGENTS.md</code> or import it into <code>OpenMausBot</code> / <code>invisible_dots</code> so your agents inherit all 10 bot roles, routine triggers, approval boundaries, and deterministic acceptance tests.
              </p>

              <pre className="p-4 bg-slate-950 text-slate-200 rounded-lg font-mono text-[11px] h-72 overflow-y-auto whitespace-pre-wrap leading-relaxed">
                {agentSpecText}
              </pre>
            </div>
          )}
        </div>
      </div>
    </div>
  );
};
